                    <div class="subheading">PRINCIPLE</div>



                    <!--texting -->

                    <div class="inrcontentpanel">

                        <div class="bodytext">Hair transplantation surgery is based on the principle of ‘Donor Dominance’. Hair at the back and sides of the scalp continue to grow throughout the life a person, even in a man with severe hair loss ( Norwood grade 7 ) .These
                            hair are resistant to the hormonal influence. When the hair is transplanted to the bald area, it continues to grow naturally, and can be washed trimmed and styled as one wants to. This donor area will permit harvesting of 4,000-5,000
                            or more grafts in most people, planned in one or multiple sessions. Future sessions of hair transplant may be needed, as the person ages and balding progresses. Though the actual pattern of hair loss is difficult to predict,
                            it is important to remember that further hair loss is likely.</div>

                    </div>

