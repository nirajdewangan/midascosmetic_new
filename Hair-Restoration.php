                        <h4>Hair loss- Facts and Myths</h4>

                    </div>

                    <!--end heading -->

                    <!--texting -->

                    <div class="inrcontentpanel">

                        <div class="bodytext"> There are many causes for hair loss in men and women. However, in the overwhelming majority of males with hair loss, the cause is Hereditary androgenetic alopecia, more commonly known as “Male pattern baldness. Similarly, most
                            females presenting with hair loss have Hereditary Female pattern hair loss. Baldness becomes noticeable when 50% of the hair is lost.</div>

                    </div>

                    <div class="inrcontentpanel">

                        <div class="bodytext">Many MYTHS abound regarding hair loss; hair loss is NOT caused by frequent shampooing, the wearing of hats or helmets, or the presence of mites. Most adults loose approximately 75–125 hairs from their scalps every day due to the
                            natural process whereby some hairs go into a dormant state (telogen), and others come out of this state and begin to sprout a new hair (anagen). As long as the process remains balanced, the number of hairs on the scalp remain
                            constant. One other minor factor in hair loss is stress, which is thought to accelerate already genetically programmed hair loss.</div>

                    </div>

                    <div class="inrcontentpanel">

                        <div class="bodytext">The tendency for male and female pattern hair loss is genetically inherited from either side of the family, and begins to develop after puberty. Hair on the scalp that is genetically susceptible to androgenetic alopecia (generally
                            the front and top of the scalp), starts to shrink in its shaft diameter and potential length during each 3 to 5 year “life cycle,” until it eventually disappears. </div>

                    </div>

