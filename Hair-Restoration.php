                    <div class="subheading">STRIP METHOD:</div>



                    <!--texting -->

                    <div class="inrcontentpanel">

                        <div class="bodytext">Hair transplant is considered to be ‘minor out-patient surgery’, can take 4–8 hours and is usually performed using local anaesthesia on an out-patient basis, occasionally with some supplemental oral or IV medication. Patients are
                            awake as usually no sedation is used. A narrow, long strip of skin is harvested from the donor areas and closed with sutures or staples. These are usually removed in 10– 14 days. Dissolvable sutures may occasionally be used
                            in order to eliminate the need for you to return for stitch removal. Using ‘Trichophytic Closure’, the scar will be better concealed, as some hair will grow through the scar. The hairs surrounding the scar will conceal it,
                            as long as they are not too short. The harvested hairs are then cut into follicular unit micro-grafts ( 1-4 hair ) under magnification. These grafts are then placed in the areas of hair loss (recipient area) with small, superficial
                            needle holes or slits in the skin of the scalp. Breaks are allowed during the surgery, for refreshments and visit to the rest room. At the end of the procedure, the donor site will have a small dressing and the transplanted
                            area has no dressing. </div>

                    </div>

                    <!--end texting -->

                    <!--heading -->

                    <div class="ipageheadingsub" style="margin:20px 0 00; background:#f6f6f6">

                        <h4>FOLLICULAR UNIT EXTRACTION (FUE)</h4>

                    </div>

                    <!--end heading -->

                    <!--procudure -->

                    <!--texting -->

                    <div class="inrcontentpanel">

                        <div class="bodytext">The FUE method of Hair transplantation varies from the ‘Strip method’ in the way the follicular grafts are harvested from the donor area. In FUE method, the follicular units are extracted one by one, using micro-punches of 0.8
                            and 1.0 mm diameter. There is no requirement for stitches as the donor area heals in a few days. FUE method is useful for people who want to keep the hair at the back very short (Buzz cut), as there is no visible linear scar.
                            Other benefits include the ability to resume strenuous activities almost immediately after the procedure and its use in corrective procedures. The main limitation of FUE compared to ‘ Strip method’ is that it is less efficient
                            in harvesting hair from the permanent zone. In cases where large sessions are planned, the entire donor area needs to be shaved leading to a significant short term cosmetic problem for many people. In contrast, in the ‘Strip
                            method’, the incision site is covered by the surrounding hair and is invisible. The cost of FUE method is more than the Strip method, per follicular graft.</div>

                    </div>

