	  <p style="margin-top: 0;">The term ‘Gynecomastia’ was coined by Galeno. Gynecomastia has been a matter of discussion and source of embarrassement since ages.</p>
<p>During puberty, hormonal changes cause the breast to enlarge in boys. This disappears over time in many cases. It persists in some cases into adulthood and is called Idiopathic gynecomastia. Gynecomastia can also be due to hormone intake( in bodybuilders), use of certain drugs or rarely due to endocrine disorders. It is a source of acute embarrassement leading to social inhibition and psychological problems.</p>
<p>Gynecomastia is due to excessive glandular tissue( True form) or more commonly a combination of glandular tissue with fat( Mixed form). Pseudo-gynaecomastia is a condition caused by excessive fat deposition and can be corrected by liposuction alone.</p>
<h2 style="
    margin-bottom: 0px;
    border-bottom: 1px dashed #000;
    padding-bottom: 1px;
    font-size: 14px;
    font-weight: bold;
    color: #000;
    border-width: 3px;
">PROCEDURE</h2>
<p>Gynecomastia can be effectively corrected by a combination of excision of glandular tissue and liposuction. It is a day-care procedure and one is discharged on the same day from the hospital. Initially, excess fat is removed from the chest and under the axilla by liposuction. A cut is then made at the junction of lower half of areola with skin and the glandular tissue is removed. In Grade 3 gynecomastia, excess skin may need removal around the areola( periareolar excision).</p>
<h2 style="
    margin-bottom: 0px;
    border-bottom: 1px dashed #000;
    padding-bottom: 1px;
    font-size: 14px;
    font-weight: bold;
    color: #000;
    border-width: 3px;
">AFTERCARE</h2>
<p>A pressure garment is worn for 3-4 weeks after surgery. Down time is 2-3 days. After the surgery, one invariably is more confident, comfortable being bare chested, leading to improvement in social interactions.</p>
