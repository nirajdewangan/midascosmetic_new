	  <p style="margin-top: 0;">The term ‘Gynecomastia’ was coined by Galeno. Gynecomastia has been a matter of discussion and source of embarrassement since ages.</p>
<p>During puberty, hormonal changes cause the breast to enlarge in boys. This disappears over time in many cases. It persists in some cases into adulthood and is called Idiopathic gynecomastia. Gynecomastia can also be due to hormone intake( in bodybuilders), use of certain drugs or rarely due to endocrine disorders. It is a source of acute embarrassement leading to social inhibition and psychological problems.</p>
<p>Gynecomastia is due to excessive glandular tissue( True form) or more commonly a combination of glandular tissue with fat( Mixed form). Pseudo-gynaecomastia is a condition caused by excessive fat deposition and can be corrected by liposuction alone.</p>
