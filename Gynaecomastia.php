">PROCEDURE</h2>
<p>Gynecomastia can be effectively corrected by a combination of excision of glandular tissue and liposuction. It is a day-care procedure and one is discharged on the same day from the hospital. Initially, excess fat is removed from the chest and under the axilla by liposuction. A cut is then made at the junction of lower half of areola with skin and the glandular tissue is removed. In Grade 3 gynecomastia, excess skin may need removal around the areola( periareolar excision).</p>
